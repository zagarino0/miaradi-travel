let currentLanguage = "fr";

function setLanguage(language) {
  currentLanguage = translations[language] ? language : "fr";
  document.documentElement.lang = currentLanguage;
  const dictionary = translations[currentLanguage];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.innerHTML = dictionary[key];
  });

  const name = document.querySelector('input[name="name"]');
  const email = document.querySelector('input[name="email"]');
  const message = document.querySelector('textarea[name="message"]');
  if (name) name.placeholder = dictionary.namePlaceholder;
  if (email) email.placeholder = dictionary.emailPlaceholder;
  if (message) message.placeholder = dictionary.messagePlaceholder;

  const languageToggle = document.querySelector(".language-toggle");
  if (languageToggle) {
    languageToggle.textContent = currentLanguage === "fr" ? "EN" : "FR";
    languageToggle.setAttribute("aria-label", currentLanguage === "fr" ? "Switch to English" : "Passer en français");
  }
  document.title = currentLanguage === "fr"
    ? "MIARADI-TRAVEL — Découvrez Madagascar autrement"
    : "MIARADI-TRAVEL — Discover Madagascar differently";
}

function initHeroSlideshow() {
  const slides = Array.from(document.querySelectorAll(".hero-slide"));
  if (slides.length < 2) return;

  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (reduceMotion) return;

  let activeIndex = slides.findIndex((slide) => slide.classList.contains("is-active"));
  if (activeIndex < 0) activeIndex = 0;

  window.setInterval(() => {
    slides[activeIndex].classList.remove("is-active");
    activeIndex = (activeIndex + 1) % slides.length;
    slides[activeIndex].classList.add("is-active");
  }, 5000);
}

